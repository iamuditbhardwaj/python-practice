# A for loop is used to iterate through a sequence like list, tuple, or string [iterables]

# for loop with list
l = [8, True, "Alex", 33.3]
for item in l:
    print(item)

# for loop with tuple
t = (324, "Hey", False, 2)
for item in t:
    print(item)

# for loop with string
s = "python"
for i in s:
    print(i)