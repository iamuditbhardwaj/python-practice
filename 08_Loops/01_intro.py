# Loops

# Sometimes we want to repeat a set of statements in our program, 
# such as printing numbers from 1 to 10000.

# Printing each number individually up to 10000 would take a lot of time and effort. 
# Instead, we use loops to repeat the same block of code automatically.

# Types of loops in Python:

# 1. While loop
#    - Repeats as long as a condition is True.

# 2. For loop
#    - Iterates over a sequence (list, tuple, string, range, etc.).

# In short, a loop is a programming construct that repeatedly executes a block of code,
# until a specified condition is met (or until all items in a sequence have been processed).