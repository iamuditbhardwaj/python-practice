# The for loop is similar to the while loop because it can perform
# many of the same tasks, such as repeating a block of code multiple times.

for i in range(0, 11):
    print(i)

# Range() function

# range() function in python is used to generate sequence of number.
# we can also specify the start, stop and step size in it.
# Syntax: range(start, stop, step size):

for i in range(0, 41, 4):
    print(i)

