# Escape Sequence Characters

# 1. \n = moves the text to next line
print("Hii, \nMy name is Alex.")

# 2. \t = adds a tab space between text
print("I \tlike to play \tfootball")

# 3. \\ = adds an actual "\" between text.
print("34\\2 is 17")

# 4. \" = adds an actual quote in words or sentence.
print("He is an \"excellent\" child")