# If else statements
# Sometimes in python, execution of some instructions are based on certain conditionls.
# syntax:
"""if(condition1):  
        print("yes")
   else:  
        print("no")"""

# Example:
a = int(input("Enter age: "))

if(a>=18):  
    print("You are adult")  

else:  
    print("You are minor") 

# When the above given condition will be true, 'if' statement will be executed.
# When the above given condition will be false, 'else' statement will be executed.